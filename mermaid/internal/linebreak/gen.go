//go:build ignore

// gen writes classes.go from the Unicode Character Database:
//
//	go run gen.go <dir>
//
// where <dir> holds LineBreak.txt, EastAsianWidth.txt, DerivedGeneralCategory.txt
// and emoji-data.txt of one Unicode version, from https://www.unicode.org/Public/.
// The version is the one Chrome's ICU carries; it is read from LineBreak.txt.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const runes = 0x110000

// entry is a line of a property file: a range and its value, or a @missing default.
var entry = regexp.MustCompile(`^(?:# @missing: )?([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)`)

// read sets each code point of the file's ranges to the value of its range, the
// @missing defaults first as the file lists them.
func read(dir, name string, set func(r rune, v string)) string {
	f, err := os.Open(filepath.Join(dir, name))
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var first string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if first == "" {
			first = line
		}
		if strings.HasPrefix(line, "#") && !strings.HasPrefix(line, "# @missing:") {
			continue
		}
		m := entry.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		lo, err := strconv.ParseUint(m[1], 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		hi := lo
		if m[2] != "" {
			if hi, err = strconv.ParseUint(m[2], 16, 32); err != nil {
				log.Fatal(err)
			}
		}
		for r := lo; r <= hi; r++ {
			set(rune(r), m[3])
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	return first
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run gen.go <dir>")
	}
	dir := os.Args[1]
	lb := make([]string, runes)
	ea := make([]string, runes)
	gc := make([]string, runes)
	pict := make([]bool, runes)
	version := read(dir, "LineBreak.txt", func(r rune, v string) { lb[r] = v })
	read(dir, "EastAsianWidth.txt", func(r rune, v string) { ea[r] = v })
	read(dir, "DerivedGeneralCategory.txt", func(r rune, v string) { gc[r] = v })
	read(dir, "emoji-data.txt", func(r rune, v string) {
		if v == "Extended_Pictographic" {
			pict[r] = true
		}
	})

	type span struct {
		lo, hi rune
		c      string
		f      []string
	}
	var spans []span
	used := map[string]bool{}
	for r := rune(0); r < runes; r++ {
		c := resolve(lb[r], gc[r])
		var f []string
		if ea[r] == "F" || ea[r] == "W" || ea[r] == "H" {
			f = append(f, "eastAsian")
		}
		if c == "QU" && gc[r] == "Pi" {
			f = append(f, "initial")
		}
		if c == "QU" && gc[r] == "Pf" {
			f = append(f, "final")
		}
		if pict[r] && gc[r] == "Cn" {
			f = append(f, "unassignedPictographic")
		}
		used[c] = true
		if n := len(spans); n > 0 && spans[n-1].c == c && slices.Equal(spans[n-1].f, f) {
			spans[n-1].hi = r
			continue
		}
		spans = append(spans, span{r, r, c, f})
	}

	for c := range used {
		if !slices.Contains(classNames, c) {
			log.Fatalf("class %s is new to gen.go", c)
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen.go from %s; DO NOT EDIT.\n\n", strings.TrimPrefix(version, "# "))
	b.WriteString("package linebreak\n\n")
	b.WriteString("// The line break classes of UAX #14, as LB1 leaves them.\n")
	b.WriteString("const (\n")
	first := true
	for _, c := range classNames {
		if !used[c] {
			continue
		}
		if first {
			fmt.Fprintf(&b, "\t%s class = iota\n", c)
			first = false
			continue
		}
		fmt.Fprintf(&b, "\t%s\n", c)
	}
	b.WriteString(")\n\n")
	b.WriteString("var spans = []span{\n")
	for _, s := range spans {
		f := "0"
		if len(s.f) > 0 {
			f = strings.Join(s.f, " | ")
		}
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %s, %s},\n", s.lo, s.hi, s.c, f)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("classes.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// resolve is LB1 as Chrome resolves it: AI, SG and XX are AL; SA is CM for its
// marks and AL otherwise; CJ is ID, as CSS line-break: normal has it.
func resolve(c, gc string) string {
	switch c {
	case "AI", "SG", "XX":
		return "AL"
	case "SA":
		if gc == "Mn" || gc == "Mc" {
			return "CM"
		}
		return "AL"
	case "CJ":
		return "ID"
	}
	return c
}

// classNames orders the classes as UAX #14 lists them.
var classNames = strings.Fields(`BK CR LF CM NL SG WJ ZW GL SP ZWJ B2 BA BB HY CB CL CP EX IN
	NS OP QU IS NU PO PR SY AI AK AL AP AS CJ EB EM H2 H3 HH HL ID JL JV JT RI SA VF VI XX`)
