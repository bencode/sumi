// Every expected drawing here comes from running elkjs 0.12.1 with Mermaid's
// options.

func box(id string, width, height float64) InputNode {
	return InputNode{ID: id, Width: width, Height: height}
}

func treeDrawing(r Result) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%vx%v\n", r.Width, r.Height)
	writeNodes(&b, r.Nodes, "")
	for _, e := range r.Edges {
		fmt.Fprintf(&b, "%s [%s]", e.ID, e.Container)
		for _, p := range e.Points {
			fmt.Fprintf(&b, " %v,%v", p.X, p.Y)
		}
		for _, l := range e.Labels {
			fmt.Fprintf(&b, " label %v,%v", l.X, l.Y)
		}
		b.WriteByte('\n')
	}
	return b.String()
}

func writeNodes(b *strings.Builder, all []PlacedNode, indent string) {
	for _, n := range all {
		fmt.Fprintf(b, "%s%s %v,%v %vx%v", indent, n.ID, n.X, n.Y, n.Width, n.Height)
		if n.Title != nil {
			fmt.Fprintf(b, " title %v,%v", n.Title.X, n.Title.Y)
		}
		b.WriteByte('\n')
		writeNodes(b, n.Children, indent+" ")
	}
}

// wideTitle has a title wider than its subgraph's content. Its minimum width is
// a minimum height when the graph goes down or up, as ELK never turns it.
func wideTitle(d Direction) Input {
	s := InputNode{
		ID: "s", Title: &Size{120, 19}, MinWidth: 128,
		Children: []InputNode{box("a", 40, 20), box("b", 40, 20)},
	}
	return Input{Direction: d, Nodes: []InputNode{box("c", 40, 20), s}, Edges: edgesOf("c>s a>b")}
}

