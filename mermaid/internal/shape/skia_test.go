// What is expected is Chrome's getBBox of the element drawn from the same numbers.
// Each box here is one the float32 of its exact extent gets wrong, or one that
// only a single step of the port gets right.

func TestCylinderRect(t *testing.T) {
	tests := []struct {
		w, h, rx, ry float64
		W, H         float32
	}{
		{275.1926726862754, 125.19126132664155, 137.5963363431377, 17.191261326641545, 275.1926574707031, 159.5570068359375},
		{539.6576330567048, 149.29833128429084, 269.8288165283524, 20.298331284290853, 539.6576538085938, 189.88096618652344},
		{522.2244112241195, 86.17169014980512, 261.11220561205977, 20.171690149805116, 522.2244262695312, 126.50114440917969},
		{178.89584849909687, 80.71687169984723, 89.44792424954844, 14.716871699847236, 178.89584350585938, 110.15061950683594},
		{202.00211320538173, 123.44348683448028, 101.00105660269087, 15.44348683448028, 202.00210571289062, 154.31980895996094},
		{217.78208175012008, 123.88342079012739, 108.89104087506004, 15.883420790127383, 217.78208923339844, 155.6502685546875},
		{228.3486627956613, 103.15604407478071, 114.17433139783066, 16.156044074780713, 228.34866333007812, 135.45697021484375},
	}
	for _, tt := range tests {
		if r := cylinderRect(tt.w, tt.h, tt.rx, tt.ry); r.w != tt.W || r.h != tt.H {
			t.Errorf("%v x %v: %v x %v, want %v x %v", tt.w, tt.h, r.w, r.h, tt.W, tt.H)
		}
	}
}

